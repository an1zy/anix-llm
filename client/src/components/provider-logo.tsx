function resolvePath(id: string, name: string) {
  const normId = id.trim().toLowerCase();
  const normName = name.trim().toLowerCase();

  const key = PROVIDER_ALIASES[normId] || PROVIDER_ALIASES[normName];
  if (key && OFFICIAL_PATHS[key]) {
    return OFFICIAL_PATHS[key];
  }
  return null;
}

function getInitials(name: string): string {
  const sanitized = name.replace(/[^a-zA-Z0-9\s]/g, ' ').trim();
  const parts = sanitized.split(/\s+/).filter(Boolean);
  if (parts.length >= 2) {
    return (parts[0][0] + parts[1][0]).toUpperCase();
  }
  return sanitized.slice(0, 2).toUpperCase() || 'AI';
}

export function ProviderLogo({ id, name, logoUrl, className = 'size-9' }: ProviderLogoProps) {
  const normId = id.trim().toLowerCase();
  const normName = name.trim().toLowerCase();
  const def = resolvePath(id, name);

  if (def) {
    const isObj = typeof def === 'object';
    const mainPath = isObj ? def.path : def;
    const clipRule = isObj ? def.clipRule : undefined;
    const extraPath = isObj ? def.extraPath : undefined;
    const viewBox = (isObj && def.viewBox) ? def.viewBox : '0 0 24 24';

    return (
      <div
        className={`${className} rounded-lg border border-border bg-card dark:bg-neutral-900 p-2 flex items-center justify-center shrink-0 shadow-inner group-hover:border-foreground/20 transition-colors`}
        title={name}
      >
        <svg viewBox={viewBox} fill="currentColor" className="size-full text-foreground dark:text-white">
          <path d={mainPath} clipRule={clipRule} />
          {extraPath && <path d={extraPath} />}
        </svg>
      </div>
    );
  }

  const effectiveLogoUrl = logoUrl || LOCAL_IMAGE_LOGOS[normId] || LOCAL_IMAGE_LOGOS[normName];

  if (effectiveLogoUrl) {
    return (
      <div
        className={`${className} rounded-lg border border-border bg-card dark:bg-neutral-900 p-1.5 flex items-center justify-center shrink-0 shadow-inner overflow-hidden group-hover:border-foreground/20 transition-colors`}
        title={name}
      >
        <img
          src={effectiveLogoUrl}
          alt={name}
          className="size-full object-contain filter dark:invert"
          loading="lazy"
        />
      </div>
    );
  }

  return (
    <div
      className={`${className} rounded-lg border border-border bg-muted dark:bg-neutral-900 text-muted-foreground dark:text-neutral-300 flex items-center justify-center font-mono font-bold text-xs shrink-0 select-none tracking-wider`}
      title={name}
    >
      {getInitials(name)}
    </div>
  );
}
